# P5.3b: does the best farm decision hold up under the spread of Maine prices and labor costs?
#
# Economic variants (MAA 2020 benchmarking Tables, established suspended oyster farms):
#   price: mean 0.72 +/- 1 SD 0.12 USD per oyster (Table 33); both size tiers scaled by the same factor;
#   labor: mean 0.37 +/- 1 SD 0.21 USD per oyster (Table 27), shifting variable_cost_per_oyster by +/- 0.21.
# 3 x 3 = 9 variants. Everything else as scripts/p5_3_grid_search.jl (10-year cycled horizon, 8 annual cohorts,
# X_K posterior-quantile scenarios). For each site and variant: the best decision by expected NPV, and the NPV
# and regret of the baseline-best decision (the best decision under mean price and mean labor).
#
# Usage: julia --project scripts/p5_3b_economic_sensitivity.jl
# Writes outputs/p5_3b/sensitivity.md and .arrow.

using OysterFarming
using Arrow, DataFrames, Dates

const ROOT = normpath(joinpath(@__DIR__, ".."))
const OUT = joinpath(ROOT, "outputs", "p5_3b")
const SITES = ["dam_lower", "dam_upper"]
const SEED_MM = 20.0
const N_COHORTS = 8
const HORIZON_YEARS = 10
const WEEKLY_CAPACITY = 10_670.0      # derivation in scripts/p5_3_grid_search.jl
const RISK_Q = 0.1
const SEED_MONTHS = [4, 5, 7, 10]
const SEEDS = [400_000.0, 800_000.0, 1_600_000.0]
const MARKET_MM = [65.0, 76.0]
const PRICE_SD = 0.12                 # MAA Table 33
const PRICE_MEAN = 0.72
const LABOR_SD = 0.21                 # MAA Table 27

P(file) = load_params(joinpath(ROOT, "params", file))
vir = P("deb_c_virginica.toml")
xk = P("deb_c_virginica_xk.toml")
qs = sort([k for k in keys(xk) if startswith(k, "X_K_posterior_q")])
scenarios = [(0.2, DEBParams(vir; X_K=xk[k].value)) for k in qs]
farm = FarmParams(merge(P("farm_damariscotta.toml"), P("deb_c_virginica_clearance.toml")))
econ0 = EconParams(P("economics_maine_maa.toml"))
nitro = NitrogenParams(P("nitrogen_chesapeake_bmp.toml"))
vib = VibrioRule(P("vibrio_maine.toml"))
forcing = read_contract(joinpath(ROOT, "data", "processed", "forcing_daily.arrow"), "forcing_daily")

full_years(b) = [y for y in unique(year.(b.date)) if count(year.(b.date) .== y) == daysinyear(y) &&
                 !any(ismissing, b.chl_ug_l[year.(b.date) .== y])]

"Economic variant: prices scaled to `price` mean, variable cost shifted by `dlabor`."
function variant(price, dlabor)
    k = price / PRICE_MEAN
    e = econ0
    return EconParams(e.price_per_oyster * k, e.seed_cost_per_seed, e.variable_cost_per_oyster + dlabor,
                      e.fixed_cost_per_year, e.capital_investment, e.discount_rate,
                      [(lo, pr * k) for (lo, pr) in e.price_tiers], e.capital_per_acre, e.seeds_per_acre,
                      e.capital_life_years)
end

rows = DataFrame(site=String[], price=Float64[], labor_shift=Float64[], best_month=Int[], best_seeds=Float64[],
                 best_market_mm=Float64[], best_npv=Float64[], baseline_npv=Float64[], regret=Float64[])
for site in SITES
    b = longest_block(forcing_for_site(forcing, site))
    f = cycle_years(b, full_years(b), HORIZON_YEARS)
    grids = Dict{Tuple{Float64,Float64},DataFrame}()
    for price in (PRICE_MEAN - PRICE_SD, PRICE_MEAN, PRICE_MEAN + PRICE_SD), dl in (-LABOR_SD, 0.0, LABOR_SD)
        setup = DecisionSetup(f, scenarios, farm, variant(price, dl), nitro, vib, WEEKLY_CAPACITY, 1.0, 0.0,
                              SEED_MM, N_COHORTS, RISK_Q)
        grids[(price, dl)] = grid_search(setup; seed_months=SEED_MONTHS, seeds_per_cohort=SEEDS, market_sizes_mm=MARKET_MM)
        println("done $site price $price labor $dl")
    end
    base = first(grids[(PRICE_MEAN, 0.0)])
    for ((price, dl), g) in sort(collect(grids); by=first)
        best = first(g)
        bl = g[(g.seed_month .== base.seed_month) .& (g.seeds_per_cohort .== base.seeds_per_cohort) .&
               (g.market_shell_height_mm .== base.market_shell_height_mm), :expected_npv][1]
        push!(rows, (site, price, dl, best.seed_month, best.seeds_per_cohort, best.market_shell_height_mm,
                     best.expected_npv, bl, best.expected_npv - bl))
    end
end

mkpath(OUT)
Arrow.write(joinpath(OUT, "sensitivity.arrow"), rows)
fmt(x) = string(round(x; digits=0))
open(joinpath(OUT, "sensitivity.md"), "w") do io
    println(io, "# P5.3b economic sensitivity (generated by scripts/p5_3b_economic_sensitivity.jl)\n")
    println(io, "Price mean $(PRICE_MEAN) +/- $(PRICE_SD) USD (MAA Table 33); labor cost shift +/- $(LABOR_SD) USD per oyster ",
            "(MAA Table 27). 10-year cycled horizon, $(N_COHORTS) annual cohorts; grid: months $(SEED_MONTHS), seeds ",
            "$(Int.(SEEDS)), market $(Int.(MARKET_MM)) mm. Baseline decision = best at mean price and labor.\n")
    println(io, "| site | price USD | labor shift USD | best decision (month, seeds, mm) | best expected NPV | baseline decision NPV | regret |")
    println(io, "|---|---|---|---|---|---|---|")
    for r in eachrow(rows)
        println(io, "| $(r.site) | $(r.price) | $(r.labor_shift) | $(r.best_month), $(Int(r.best_seeds)), $(Int(r.best_market_mm)) | ",
                "$(fmt(r.best_npv)) | $(fmt(r.baseline_npv)) | $(fmt(r.regret)) |")
    end
end
println(read(joinpath(OUT, "sensitivity.md"), String))
