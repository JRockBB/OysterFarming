# P4.3: Dermo screen for Damariscotta under present temperatures and delta-change warming.
#
# Model: Ragone Calvo et al. (2001) with the published parameters (params/dermo_ragone_calvo2001.toml).
# P4.2 found that this model does NOT reproduce Maryland bar intensities (it overpredicts by ~3 units), so
# this is a screen, not a forecast: it asks whether Maine water is warm enough for the parasite to multiply.
# Assumption (stated): the parasite is present, i.e. the annual transmission event occurs. Start P = 0.
# Warming: +0.5, +1, +2 degC added to every day's temperature (PLAN.md P5.4 delta change; scenario inputs).
# Critical intensity: MD DNR "high range" >= 3.0 (params/dermo_thresholds_mddnr.toml).
# Reference row: a Maryland bar (Hog Island) under the same model, for scale.
#
# Usage: julia --project scripts/p4_3_dermo_maine.jl
# Writes outputs/p4_3/dermo_maine.md and .arrow.

using OysterFarming
using Arrow, DataFrames, Dates, Statistics

const ROOT = normpath(joinpath(@__DIR__, ".."))
const OUT = joinpath(ROOT, "outputs", "p4_3")
const SITES = ["dam_lower", "dam_upper", "mddnr_hog_island"]
const WARMING_C = [0.0, 0.5, 1.0, 2.0]

p = DermoParams(load_params(joinpath(ROOT, "params", "dermo_ragone_calvo2001.toml")))
critical = load_params(joinpath(ROOT, "params", "dermo_thresholds_mddnr.toml"))["critical_mean_intensity"].value
forcing = read_contract(joinpath(ROOT, "data", "processed", "forcing_daily.arrow"), "forcing_daily")

"Longest run of consecutive days with temperature and salinity present (Dermo needs no chlorophyll)."
function ts_block(site)
    f = forcing_for_site(forcing, site)
    f = f[.!ismissing.(f.temp_c) .& .!ismissing.(f.salinity_psu), :]
    blocks = continuous_blocks(f.date)
    b = blocks[argmax(length.(blocks))]
    return DataFrame(date=f.date[b], temp_c=Float64.(f.temp_c[b]), salinity_psu=Float64.(f.salinity_psu[b]))
end

rows = DataFrame(site=String[], warming_c=Float64[], years=Int[], division_days_per_yr=Float64[],
                 mean_salinity=Float64[], transmission_cells=Float64[], peak_P_median=Float64[],
                 amplification_median=Float64[], nov1_intensity_median=Float64[], first_critical=String[],
                 excess_mortality_yr=Float64[])
mort = load_params(joinpath(ROOT, "params", "dermo_mortality_mddnr.toml"))["dermo_mortality_per_intensity_yr"].value
for site in SITES
    f0 = ts_block(site)
    for dT in WARMING_C
        f = transform(f0, :temp_c => (t -> t .+ dT) => :temp_c)
        sim = simulate_dermo(p, f, 0.0)
        yrs = [y for y in unique(year.(f.date)) if Date(y, 1, 1) >= first(f.date) && Date(y, 12, 31) <= last(f.date)]
        div_days = [count((year.(f.date) .== y) .& (f.temp_c .> p.div_T_min_c)) for y in yrs]
        peak, amp, nov = Float64[], Float64[], Float64[]
        for y in yrs
            sel = (year.(sim.date) .== y) .& (dayofyear.(sim.date) .>= p.transmission_doy)
            any(sel) || continue
            tday = findfirst((year.(f.date) .== y) .& (dayofyear.(f.date) .== p.transmission_doy))
            input = dermo_transmission_cells(f.salinity_psu[tday], p)
            push!(peak, maximum(sim.P_cells_g[sel]))
            push!(amp, input > 0 ? maximum(sim.P_cells_g[sel]) / (sim.P_cells_g[tday]) : NaN)
            i = findfirst(sim.date .== Date(y, 11, 1))
            i === nothing || push!(nov, cells_to_intensity(sim.P_cells_g[i]))
        end
        intens = cells_to_intensity.(sim.P_cells_g)
        ic = findfirst(>=(critical), intens)
        push!(rows, (site, dT, length(yrs), mean(div_days), mean(f.salinity_psu),
                     median(dermo_transmission_cells.(f.salinity_psu[dayofyear.(f.date) .== p.transmission_doy], Ref(p))),
                     median(peak), median(filter(!isnan, amp)), median(nov),
                     ic === nothing ? "never" : string(sim.date[ic]),
                     mort * mean(intens)))
    end
end

mkpath(OUT)
Arrow.write(joinpath(OUT, "dermo_maine.arrow"), rows)
fmt(x; d=2) = string(round(x; digits=d))
open(joinpath(OUT, "dermo_maine.md"), "w") do io
    println(io, "# P4.3 Dermo screen, Maine vs Maryland (generated by scripts/p4_3_dermo_maine.jl)\n")
    println(io, "Published Ragone Calvo et al. (2001) model, parasite assumed present (annual transmission on day ",
            "$(p.transmission_doy)), P = 0 at the start of each site's longest temperature+salinity block. ",
            "Division only above $(p.div_T_min_c) degC. Critical: mean intensity >= $(critical) (MD DNR high range). ",
            "P4.2 showed the model overpredicts Maryland intensities, so intensities here are upper-bound screens.\n")
    println(io, "| site | warming degC | years | division days/yr | mean salinity | transmission cells/g | median annual peak P (cells/g) | median amplification (peak / P on transmission day) | median 1 Nov intensity | first day >= critical | excess mortality yr^-1 (mean) |")
    println(io, "|---|---|---|---|---|---|---|---|---|---|---|")
    for r in eachrow(rows)
        println(io, "| $(r.site) | $(r.warming_c) | $(r.years) | $(fmt(r.division_days_per_yr; d=1)) | $(fmt(r.mean_salinity; d=1)) | ",
                "$(Int(r.transmission_cells)) | $(round(r.peak_P_median; sigdigits=3)) | $(fmt(r.amplification_median)) | ",
                "$(fmt(r.nov1_intensity_median)) | $(r.first_critical) | $(fmt(r.excess_mortality_yr; d=3)) |")
    end
    println(io, "\nAmplification 1 means the parasite never multiplied after the transmission input; the intensity then ",
            "reflects only the transmission input converted with Bushek et al. (1994), which P4.2 found too high.")
    println(io, "Caveats: Maine P. marinus strains and oyster hosts may differ from Chesapeake ones; warming ignores ",
            "changes in salinity and food; excess mortality uses the Maryland fit (params/dermo_mortality_mddnr.toml).")
end
println(read(joinpath(OUT, "dermo_maine.md"), String))
