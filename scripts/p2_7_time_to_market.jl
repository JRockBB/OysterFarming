# P2.7: time to market for eastern oysters at the Maine sites, by seeding month.
#
# Model: params/deb_c_virginica.toml (Lavaud et al. 2017) with X_K from
# params/deb_c_virginica_xk.toml (P2.6). Because X_K is weakly identified by the
# calibration data, every case is run at the calibrated X_K and at both ends of its
# Bayesian 95 % interval (read from the notes of that file), giving a range.
#
# Forcing: data/processed/forcing_daily.arrow, longest unbroken block per Maine site; each run
# stops at the first day without chlorophyll (the horizon column shows the run length).
# Scenario inputs (not parameters): seed shell height (default 20 mm, first CLI argument),
# market size 76 mm (PLAN.md P2.7), seeding on the 15th of each month, initial reserve at
# equilibrium with the mean chlorophyll of the first 14 days after seeding.
#
# Usage: julia --project scripts/p2_7_time_to_market.jl [seed_shell_height_mm]
# Writes outputs/p2_7/time_to_market.md and .arrow.

using OysterFarming
using Arrow, DataFrames, Dates, Statistics, TOML

const ROOT = normpath(joinpath(@__DIR__, ".."))
const OUT = joinpath(ROOT, "outputs", "p2_7")
const MARKET_MM = 76.0
const SEED_MM = isempty(ARGS) ? 20.0 : parse(Float64, ARGS[1])
const INIT_FOOD_DAYS = 14

xk_file = joinpath(ROOT, "params", "deb_c_virginica_xk.toml")
xk_param = load_params(xk_file)["X_K"]
m = match(r"Bayesian ([0-9.]+) to ([0-9.]+)", xk_param.notes)
m === nothing && error("could not read the Bayesian interval from $(xk_file) notes")
xk_cases = [("low X_K (95% lower)", parse(Float64, m[1])), ("calibrated X_K", Float64(xk_param.value)),
            ("high X_K (95% upper)", parse(Float64, m[2]))]

params = DEBParams(load_params(joinpath(ROOT, "params", "deb_c_virginica.toml")); X_K=xk_param.value)
forcing = read_contract(joinpath(ROOT, "data", "processed", "forcing_daily.arrow"), "forcing_daily")

rows = DataFrame(site_id=String[], seed_date=Date[], xk_case=String[], X_K=Float64[],
                 days_to_market=Union{Int,Missing}[], years_to_market=Union{Float64,Missing}[], horizon_days=Int[])
for site in ("dam_lower", "dam_upper")
    block = longest_block(forcing_for_site(forcing, site))
    y0, y1 = year(first(block.date)), year(last(block.date))
    for y in y0:y1, mo in 1:12
        seed = Date(y, mo, 15)
        (seed < first(block.date) || seed + Day(INIT_FOOD_DAYS) > last(block.date)) && continue
        run = block[block.date .>= seed, :]
        gap = findfirst(ismissing, run.chl_ug_l)      # stop at the first day without chlorophyll
        gap === nothing || (run = run[1:gap-1, :])
        nrow(run) > INIT_FOOD_DAYS || continue
        food0 = mean(run.chl_ug_l[1:INIT_FOOD_DAYS])
        for (label, xk) in xk_cases
            p = with_values(params; X_K=xk)
            u0 = initial_state(p; shell_height_mm=SEED_MM, e=functional_response(food0, xk))
            d = time_to_market(p, run, seed, u0; market_shell_height_mm=MARKET_MM)
            push!(rows, (site, seed, label, xk, d === nothing ? missing : d,
                         d === nothing ? missing : d / 365.25, nrow(run)))
        end
    end
end

mkpath(OUT)
Arrow.write(joinpath(OUT, "time_to_market.arrow"), rows)
fmt(x) = ismissing(x) ? "not reached" : string(round(x; digits=2))
open(joinpath(OUT, "time_to_market.md"), "w") do io
    println(io, "# P2.7 time to market, Damariscotta sites (generated by scripts/p2_7_time_to_market.jl)\n")
    println(io, "Seed $(SEED_MM) mm to market $(MARKET_MM) mm. X_K cases: ",
            join(["$(l) = $(round(x; digits=2))" for (l, x) in xk_cases], "; "), " ug chl-a/L.\n")
    println(io, "\"not reached\" means market size was not reached before the forcing block ends (horizon shown).\n")
    for site in unique(rows.site_id)
        println(io, "## $(site)\n")
        println(io, "| seeding date | horizon (yr) | years, low X_K | years, calibrated | years, high X_K |")
        println(io, "|---|---|---|---|---|")
        s = rows[rows.site_id .== site, :]
        for g in groupby(s, :seed_date; sort=true)
            v = Dict(r.xk_case => r.years_to_market for r in eachrow(g))
            println(io, "| $(g.seed_date[1]) | $(round(g.horizon_days[1] / 365.25; digits=1)) | ",
                    "$(fmt(v[xk_cases[1][1]])) | $(fmt(v[xk_cases[2][1]])) | $(fmt(v[xk_cases[3][1]])) |")
        end
        println(io)
    end
    println(io, "Sanity check (PLAN.md P2.7): UMaine work reports 2-5 years to market for most of coastal Maine.")
end
println(read(joinpath(OUT, "time_to_market.md"), String))
