# P5.5: headline "does warming help or hurt" tables and figure for the Damariscotta sites.
#
# Reads the outputs of scripts/p5_4_climate_scenarios.jl (growth, farm decision, NPV, nitrogen) and
# scripts/p4_3_dermo_maine.jl (Dermo screen); run those first. Changes are relative to the 0 degC row.
# Vibrio: the Maine rule (params/vibrio_maine.toml) is a fixed calendar window, so its days per year do
# not change with warming; reported for completeness.
# Dermo rows are an upper-bound screen (model failed Maryland validation, PLAN.md P4.2) and are not
# included in the NPV.
#
# Usage: julia --project=scripts/figures scripts/p5_5_headline.jl
#   (scripts/figures is a separate environment with CairoMakie and this package developed in)
# Writes outputs/p5_5/headline.md and headline.png.

using OysterFarming
using Arrow, CairoMakie, DataFrames, Dates

const ROOT = normpath(joinpath(@__DIR__, ".."))
const OUT = joinpath(ROOT, "outputs", "p5_5")

read_out(task, file) = DataFrame(Arrow.Table(joinpath(ROOT, "outputs", task, file)))
sc = read_out("p5_4", "scenarios.arrow")
dm = read_out("p4_3", "dermo_maine.arrow")
vib = VibrioRule(load_params(joinpath(ROOT, "params", "vibrio_maine.toml")))
vib_days = count(d -> in_vibrio_control(d, vib), Date(2019, 1, 1):Day(1):Date(2019, 12, 31))

df = leftjoin(sc, select(dm, :site, :warming_c, :excess_mortality_yr => :dermo_excess_mortality_yr,
                         :amplification_median => :dermo_amplification); on=[:site, :warming_c])
sort!(df, [:site, :warming_c])
base = Dict(r.site => r for r in eachrow(df) if r.warming_c == 0.0)
delta(r, col) = (ismissing(r[col]) || ismissing(base[r.site][col])) ? missing : r[col] - base[r.site][col]

fmt(x; d=2) = ismissing(x) ? "n/a" : string(round(x; digits=d))
sgn(x; d=2) = ismissing(x) ? "n/a" : (x > 0 ? "+" : "") * string(round(x; digits=d))
mkpath(OUT)
open(joinpath(OUT, "headline.md"), "w") do io
    println(io, "# P5.5 headline: does warming help or hurt? (generated by scripts/p5_5_headline.jl)\n")
    println(io, "Changes relative to present temperatures (0 degC). Food and salinity unchanged. NPV carries the P5.3 caveats ",
            "(MAA-derived harvest capacity, horizon truncation with straight-line salvage, 2019 Maine costs): compare rows, not absolutes.\n")
    println(io, "## Growth and economics\n")
    println(io, "| site | warming degC | change in years to market (May seed) | change (Oct seed) | best decision (month, seeds/cohort) | change in expected NPV USD | change in q0.1 NPV USD | change in N removed kg |")
    println(io, "|---|---|---|---|---|---|---|---|")
    for r in eachrow(df)
        println(io, "| $(r.site) | $(r.warming_c) | $(sgn(delta(r, :ttm_may_yr))) | $(sgn(delta(r, :ttm_oct_yr))) | ",
                "$(r.best_seed_month), $(Int(r.best_seeds)) | $(sgn(delta(r, :best_expected_npv); d=0)) | ",
                "$(sgn(delta(r, :best_lower_npv); d=0)) | $(sgn(delta(r, :best_nitrogen_kg); d=1)) |")
    end
    println(io, "\n## Risk\n")
    println(io, "| site | warming degC | Dermo division days/yr | Dermo amplification (median) | Dermo excess mortality yr^-1 (upper bound) | Vibrio control days/yr |")
    println(io, "|---|---|---|---|---|---|")
    for r in eachrow(df)
        println(io, "| $(r.site) | $(r.warming_c) | $(fmt(r.dermo_division_days_yr; d=1)) | $(fmt(r.dermo_amplification)) | ",
                "$(fmt(r.dermo_excess_mortality_yr; d=3)) | $(vib_days) |")
    end
    println(io, "\nDermo excess mortality is not interpretable as a level: where amplification is 1 the parasite never ",
            "multiplied and the value comes only from the assumed transmission input under the Bushek conversion that ",
            "failed validation (PLAN.md P4.2). Use the division days and amplification columns for the direction of change.")
    println(io, "\nReading: warming shortens time to market and raises NPV at both sites (growth is temperature-limited in ",
            "Maine). It also lengthens the season in which Dermo can multiply; at the lower estuary multiplication only ",
            "starts with about 1 degC of warming. The disease cost is not in the NPV, so the NPV gains are upper bounds.")
end

fig = Figure(size=(1000, 750))
panels = [(:ttm_may_yr, "Years to market (May seed)"), (:best_expected_npv, "Best expected NPV (USD)"),
          (:dermo_division_days_yr, "Dermo division days per year"), (:best_nitrogen_kg, "Nitrogen removed (kg)")]
for (i, (col, label)) in enumerate(panels)
    ax = Axis(fig[fldmod1(i, 2)...]; xlabel="Warming (°C)", ylabel=label)
    for g in groupby(df, :site)
        ok = .!ismissing.(g[!, col])
        scatterlines!(ax, g.warming_c[ok], Float64.(g[ok, col]); label=g.site[1])
    end
    i == 1 && axislegend(ax; position=:rt)
end
save(joinpath(OUT, "headline.png"), fig)
println(read(joinpath(OUT, "headline.md"), String))
