# P2.6: calibrate the eastern oyster food half-saturation X_K and validate on a held-out site.
#
# Data (all measured; see data/processed/forcing_report.md and docs/PLAN.md P1.9, P2.6):
#   growth: Kingsley-Smith triploid cohorts, Zenodo 10.5281/zenodo.11205266 (growth_obs.arrow)
#   forcing: CO-OPS temperature, CBP DataHub grab salinity/chlorophyll, NERRS fills (forcing_daily.arrow)
# Model: params/deb_c_virginica.toml (Lavaud et al. 2017). Triploids are run with spawning
# disabled (GSI_spawn = Inf) because they are functionally sterile.
#
# Calibration site: Patuxent River. Held-out validation site: York River (whole site held out).
# Fitted: X_K only. A two-parameter fit (X_K, p_Am) was tried and rejected: the parameters are
# not identifiable from one cohort (intervals span zero) and held-out error rose from ~2 to ~10 mm.
#
# Choices (stated, not parameters):
# - Initial shell height = observed mean on the first sampling date; the model starts that day.
# - Initial reserve at equilibrium with food: e0 = f(mean chlorophyll over the first 14 days).
# - Observation error prior for the Bayesian fit: sigma ~ HalfNormal(10 mm).
#
# Usage: julia --project scripts/p2_6_virginica_calibration.jl
# Writes outputs/p2_6/{metrics.md, predictions.arrow} and params/deb_c_virginica_xk.toml.

using OysterFarming
using Arrow, DataFrames, Dates, Random, Statistics

const ROOT = normpath(joinpath(@__DIR__, ".."))
const OUT = joinpath(ROOT, "outputs", "p2_6")
const XK_BOUNDS = (0.1, 50.0)          # ug chl-a / L, search bounds only
const SIGMA_PRIOR_MM = 10.0
const INIT_FOOD_DAYS = 14

vir = load_params(joinpath(ROOT, "params", "deb_c_virginica.toml"))
base = with_values(DEBParams(vir; X_K=5.0); GSI_spawn=Inf)
forcing = read_contract(joinpath(ROOT, "data", "processed", "forcing_daily.arrow"), "forcing_daily")
growth = read_contract(joinpath(ROOT, "data", "processed", "growth_obs.arrow"), "growth_obs")

struct Cohort
    site::String
    cohort::String
    forcing::DataFrame
    obs::DataFrame
    u0::Function
end

function cohort(site, cohort_id)
    obs = sort(growth[growth.cohort_id .== cohort_id, :], :date)
    f = forcing_for_site(forcing, site)
    f = f[f.date .>= obs.date[1], :]
    f = f[continuous_blocks(f.date)[1], :]
    obs = obs[obs.date .<= last(f.date), :]
    sh0 = Float64(obs.shell_height_mm[1])
    food0 = mean(skipmissing(f.chl_ug_l[1:INIT_FOOD_DAYS]))
    u0 = p -> initial_state(p; shell_height_mm=sh0, e=functional_response(food0, p.X_K))
    return Cohort(site, cohort_id, f, obs, u0)
end

calib_problem(c::Cohort) = CalibrationProblem(base, c.forcing, c.u0, c.obs.date[2:end],
                                              Float64.(c.obs.shell_height_mm[2:end]);
                                              names=[:X_K], lower=[XK_BOUNDS[1]], upper=[XK_BOUNDS[2]])

function predictions(c::Cohort, X_K)
    p = with_values(base; X_K=X_K)
    sim = simulate_individual(p, c.forcing, c.u0(p))
    idx = indexin(c.obs.date, sim.date)
    return DataFrame(site_id=c.site, cohort_id=c.cohort, date=c.obs.date,
                     obs_shell_height_mm=Float64.(c.obs.shell_height_mm), pred_shell_height_mm=sim.shell_height_mm[idx],
                     obs_dry_tissue_g=collect(c.obs.dry_tissue_g), pred_dry_tissue_g=sim.dry_tissue_g[idx])
end

function metrics(df, obscol, predcol)
    d = df[2:end, :]                         # first date is the initial condition
    ok = .!ismissing.(d[!, obscol])
    o, p = Float64.(d[ok, obscol]), Float64.(d[ok, predcol])
    return (n=length(o), rmse=sqrt(mean((p .- o) .^ 2)), bias=mean(p .- o),
            mape=100 * mean(abs.(p .- o) ./ o))
end

patuxent = cohort("ches_patuxent_ks", "ks2009_patuxent_3n")
york = cohort("ches_york_ks", "ks2009_york_3n")
cp = calib_problem(patuxent)

println("Least squares ...")
ls = fit_least_squares(cp, [5.0])
println("Bayesian (NUTS) ...")
bayes = fit_bayesian(Xoshiro(20261013), cp; sigma_prior_scale_mm=SIGMA_PRIOR_MM, n_samples=1000, n_adapt=500)
xk_draws = [d[1] for d in vec(collect(bayes.chain[:θ]))]
xk_median = median(xk_draws)

pred = vcat(predictions(patuxent, ls.estimate[1]), predictions(york, ls.estimate[1]))
m = Dict((s, v) => metrics(pred[pred.site_id .== s, :], Symbol("obs_", v), Symbol("pred_", v))
         for s in ("ches_patuxent_ks", "ches_york_ks"), v in ("shell_height_mm", "dry_tissue_g"))

mkpath(OUT)
Arrow.write(joinpath(OUT, "predictions.arrow"), pred)
fmt(x) = string(round(x; digits=2))
open(joinpath(OUT, "metrics.md"), "w") do io
    println(io, "# P2.6 eastern oyster calibration (generated by scripts/p2_6_virginica_calibration.jl)\n")
    println(io, "Calibration: X_K on Patuxent shell height ($(nrow(patuxent.obs) - 1) dates after the start). Held out: York.\n")
    println(io, "| method | X_K (ug chl-a/L) | 95 % interval | residual sd (mm) |")
    println(io, "|---|---|---|---|")
    println(io, "| least squares | $(fmt(ls.estimate[1])) | $(fmt(ls.lower_ci[1])) to $(fmt(ls.upper_ci[1])) (Gauss-Newton) | $(fmt(ls.sigma_mm)) |")
    println(io, "| Bayesian NUTS | median $(fmt(xk_median)) | $(fmt(bayes.lower_ci[1])) to $(fmt(bayes.upper_ci[1])) | $(fmt(bayes.sigma_mean_mm)) |")
    println(io, "\nValidation with the least-squares X_K (first date excluded: it is the initial condition):\n")
    println(io, "| site | role | variable | n | RMSE | bias (pred - obs) | MAPE % |")
    println(io, "|---|---|---|---|---|---|---|")
    for s in ("ches_patuxent_ks", "ches_york_ks"), v in ("shell_height_mm", "dry_tissue_g")
        r = m[(s, v)]
        role = s == "ches_patuxent_ks" ? "calibration" : "held out"
        println(io, "| $s | $role | $v | $(r.n) | $(fmt(r.rmse)) | $(fmt(r.bias)) | $(fmt(r.mape)) |")
    end
    println(io, "\nObserved vs predicted:\n")
    println(io, "| site | date | shell height obs | pred | dry tissue obs | pred |")
    println(io, "|---|---|---|---|---|---|")
    for r in eachrow(pred)
        println(io, "| $(r.site_id) | $(r.date) | $(fmt(r.obs_shell_height_mm)) | $(fmt(r.pred_shell_height_mm)) | ",
                "$(ismissing(r.obs_dry_tissue_g) ? "" : fmt(r.obs_dry_tissue_g)) | $(fmt(r.pred_dry_tissue_g)) |")
    end
    println(io, "\nNote: Chesapeake chlorophyll here averages ~16 ug/L, far above the fitted X_K, so these",
            " oysters fed near saturation and the data bound X_K mainly from above. Growth at low-chlorophyll",
            " sites (e.g. Damariscotta, ~2-3 ug/L) is sensitive to X_K; carry the interval forward.")
end

open(joinpath(ROOT, "params", "deb_c_virginica_xk.toml"), "w") do io
    println(io, "title = \"Calibrated food half-saturation for the eastern oyster (PLAN.md P2.6)\"\n")
    println(io, "[X_K]")
    println(io, "value = $(round(ls.estimate[1]; sigdigits=4))")
    println(io, "units = \"ug chl-a L^-1\"")
    println(io, "source = \"Calibrated in this project: scripts/p2_6_virginica_calibration.jl, least squares on Kingsley-Smith Patuxent triploid shell heights (Zenodo 10.5281/zenodo.11205266) with measured forcing (CO-OPS 8577330, CBP LE1.3, NERRS cbmrrwq); results in outputs/p2_6/metrics.md\"")
    println(io, "notes = \"95 % intervals: Gauss-Newton $(fmt(ls.lower_ci[1])) to $(fmt(ls.upper_ci[1])); Bayesian $(fmt(bayes.lower_ci[1])) to $(fmt(bayes.upper_ci[1])) (median $(fmt(xk_median))). Held-out York shell-height RMSE $(fmt(m[("ches_york_ks", "shell_height_mm")].rmse)) mm. Weakly identified: calibration site food was near saturation.\"")
    for q in (0.1, 0.3, 0.5, 0.7, 0.9)
        name = "X_K_posterior_q$(lpad(round(Int, 100q), 2, '0'))"
        println(io, "
[$(name)]")
        println(io, "value = $(round(quantile(xk_draws, q); sigdigits=4))")
        println(io, "units = \"ug chl-a L^-1\"")
        println(io, "source = \"Bayesian posterior quantile $(q) of X_K from scripts/p2_6_virginica_calibration.jl (NUTS, 1000 draws), same data as X_K\"")
        println(io, "notes = \"The 0.1/0.3/0.5/0.7/0.9 quantiles each stand for 20 % of posterior probability in decision analyses (P5.2).\"")
    end
end

println(read(joinpath(OUT, "metrics.md"), String))
