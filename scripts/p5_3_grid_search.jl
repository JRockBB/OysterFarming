# P5.2-P5.3: best seeding month, seeding density and market size for a Damariscotta farm,
# by expected NPV over eastern oyster parameter uncertainty.
#
# Biology: params/deb_c_virginica.toml with X_K at the 0.1/0.3/0.5/0.7/0.9 posterior quantiles from
# params/deb_c_virginica_xk.toml (each weighted 0.2). Diploid settings (spawning rule active).
# Farm: params/farm_damariscotta.toml (+ clearance rate); economics: params/economics_reference_farm.toml;
# nitrogen: params/nitrogen_chesapeake_bmp.toml (diploid tissue regression); Vibrio: params/vibrio_maine.toml.
# Forcing: longest unbroken block of data/processed/forcing_daily.arrow for the site.
#
# Scenario inputs (not parameters; change below): seed size 20 mm, 2 yearly cohorts, weekly harvest capacity
# 10,000 oysters, no Vibrio capacity reduction and no Vibrio handling cost (no published estimate), risk
# quantile 0.1 for the lower-NPV objective.
#
# Usage: julia --project scripts/p5_3_grid_search.jl [site_id]
# Writes outputs/p5_3/grid_<site>.md and .arrow.

using OysterFarming
using Arrow, DataFrames, Dates

const ROOT = normpath(joinpath(@__DIR__, ".."))
const OUT = joinpath(ROOT, "outputs", "p5_3")
site = isempty(ARGS) ? "dam_upper" : ARGS[1]

const SEED_MM = 20.0
const N_COHORTS = 2
const WEEKLY_CAPACITY = 10_000.0
const VIBRIO_CAPACITY_FACTOR = 1.0
const VIBRIO_COST_PER_OYSTER = 0.0
const RISK_Q = 0.1
const SEED_MONTHS = 4:10
const SEEDS = [100_000.0, 200_000.0, 400_000.0, 800_000.0, 1_600_000.0, 3_200_000.0]
const MARKET_MM = [65.0, 76.0, 90.0]

P(file) = load_params(joinpath(ROOT, "params", file))
vir = P("deb_c_virginica.toml")
xk = P("deb_c_virginica_xk.toml")
qs = sort([k for k in keys(xk) if startswith(k, "X_K_posterior_q")])
length(qs) == 5 || error("rerun scripts/p2_6_virginica_calibration.jl to export X_K posterior quantiles")
scenarios = [(0.2, DEBParams(vir; X_K=xk[k].value)) for k in qs]

setup = DecisionSetup(longest_block(forcing_for_site(read_contract(joinpath(ROOT, "data", "processed",
                                                                         "forcing_daily.arrow"), "forcing_daily"), site)),
                      scenarios,
                      FarmParams(merge(P("farm_damariscotta.toml"), P("deb_c_virginica_clearance.toml"))),
                      EconParams(P("economics_reference_farm.toml")), NitrogenParams(P("nitrogen_chesapeake_bmp.toml")),
                      VibrioRule(P("vibrio_maine.toml")), WEEKLY_CAPACITY, VIBRIO_CAPACITY_FACTOR,
                      VIBRIO_COST_PER_OYSTER, SEED_MM, N_COHORTS, RISK_Q)

g = grid_search(setup; seed_months=SEED_MONTHS, seeds_per_cohort=SEEDS, market_sizes_mm=MARKET_MM)
mkpath(OUT)
Arrow.write(joinpath(OUT, "grid_$(site).arrow"), g)
fmt(x) = string(round(x; digits=0))
open(joinpath(OUT, "grid_$(site).md"), "w") do io
    println(io, "# P5.3 grid search, $(site) (generated by scripts/p5_3_grid_search.jl)\n")
    println(io, "Forcing block $(first(setup.forcing.date)) to $(last(setup.forcing.date)); X_K scenarios ",
            join([string(round(xk[k].value; digits=2)) for k in qs], ", "), " ug/L (each 20 %). ",
            "$(N_COHORTS) cohorts, seed $(SEED_MM) mm, capacity $(Int(WEEKLY_CAPACITY))/week. ",
            "Oysters unharvested at the end of the block have no value.\n")
    println(io, "Top 10 by expected NPV (USD):\n")
    println(io, "| seed month | seeds/cohort | market mm | expected NPV | NPV at q$(RISK_Q) | harvested | N removed kg |")
    println(io, "|---|---|---|---|---|---|---|")
    for r in eachrow(first(g, 10))
        println(io, "| $(r.seed_month) | $(Int(r.seeds_per_cohort)) | $(Int(r.market_shell_height_mm)) | $(fmt(r.expected_npv)) | ",
                "$(fmt(r.lower_npv)) | $(fmt(r.expected_harvested)) | $(round(r.expected_nitrogen_kg; digits=1)) |")
    end
    best_risk = first(sort(g, :lower_npv; rev=true))
    println(io, "\nBest by the risk-averse objective (q$(RISK_Q) NPV): seed month $(best_risk.seed_month), ",
            "$(Int(best_risk.seeds_per_cohort)) seeds, market $(Int(best_risk.market_shell_height_mm)) mm, ",
            "q$(RISK_Q) NPV $(fmt(best_risk.lower_npv)), expected NPV $(fmt(best_risk.expected_npv)).")
end
println(read(joinpath(OUT, "grid_$(site).md"), String))
