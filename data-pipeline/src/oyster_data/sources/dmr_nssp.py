"""Maine DMR NSSP shellfish growing-area classifications (PLAN.md P1.5, bacterial part).

Source: Maine DMR ArcGIS Online organization (public), e.g.
https://services1.arcgis.com/RbMX0mRVOFNTdLzd/arcgis/rest/services/MaineDMR_Public_Health_2025_NSSP_Classifications/FeatureServer/81
Fields used: GA (growing area), GA_SECTION, NSSP (A approved, CA conditionally approved, R restricted,
CR conditionally restricted, P prohibited), CA_TYPE, CA_DETAIL, D_EFFECTIVE (epoch ms).

Conversion to closures rows (a processing choice, recorded in PLAN.md P1.5):
- P, R, CR sections are closed to direct harvest: closure_type "pollution", start D_EFFECTIVE, no end.
- CA sections with CA_DETAIL "Closed M/D to M/D" (seasonal rule): one "pollution" row per year from the
  effective year to `last_year`.
- CA sections tied to a wastewater plant (CA_TYPE WWTP) are open unless the plant fails; failure events
  are not published, so no rows are written (listed in the report instead).
- A sections give no rows.
Only the classification layer of one year is used (the latest by default); past layers (2015-2024)
exist but section ids differ between years.
"""

from __future__ import annotations

import json
import re
from collections.abc import Callable
from datetime import date, datetime, timezone
from pathlib import Path

import pyarrow as pa

from oyster_data.contract import SPECS, arrow_schema, validate_table
from oyster_data.paths import RAW_DIR
from oyster_data.raw import http_get, save_raw

BASE = "https://services1.arcgis.com/RbMX0mRVOFNTdLzd/arcgis/rest/services"
LAYERS = {2025: ("MaineDMR_Public_Health_2025_NSSP_Classifications", 81),
          2024: ("MaineDMR_Public_Health_2024_NSSP_Classifications", 10)}
RAW_SUBDIR = "dmr_nssp"
CLOSED_CLASSES = {"P", "R", "CR"}
SEASONAL = re.compile(r"Closed\s+(\d{1,2})/(\d{1,2})\s+to\s+(\d{1,2})/(\d{1,2})", re.I)


def query_url(year: int, growing_area: str) -> str:
    service, layer = LAYERS[year]
    return (f"{BASE}/{service}/FeatureServer/{layer}/query?where=GA%3D%27{growing_area}%27"
            "&outFields=*&returnGeometry=false&f=json")


def raw_path(year: int, growing_area: str, raw_dir: Path = RAW_DIR) -> Path:
    return raw_dir / RAW_SUBDIR / f"nssp{year}_{growing_area}.json"


def fetch(year: int, growing_area: str, raw_dir: Path = RAW_DIR,
          get: Callable[[str], bytes] = http_get, overwrite: bool = False) -> Path:
    body = get(query_url(year, growing_area))
    data = json.loads(body)
    if "features" not in data:
        raise RuntimeError(f"NSSP {year} {growing_area}: {data.get('error')}")
    return save_raw(body, raw_path(year, growing_area, raw_dir), overwrite=overwrite)


def _date(ms) -> date | None:
    return None if ms is None else datetime.fromtimestamp(ms / 1000, tz=timezone.utc).date()


def to_rows(data: dict, year: int, last_year: int) -> tuple[list[dict], list[str]]:
    """Closures rows and report notes for one growing area's features."""
    rows, notes = [], []
    src = f"maine_dmr:nssp_classification_{year}"
    for f in data["features"]:
        a = f["attributes"]
        ga, sec, cls = a["GA"], a.get("GA_SECTION"), (a.get("NSSP") or "").strip()
        detail = (a.get("CA_DETAIL") or "").strip()
        start = _date(a.get("D_EFFECTIVE"))
        area_id = f"{ga}:{sec}"
        if cls in CLOSED_CLASSES:
            if start is None:
                notes.append(f"{area_id} ({cls}) has no effective date; skipped")
                continue
            rows.append({"growing_area": ga, "area_id": area_id, "start_date": start, "end_date": None,
                         "closure_type": "pollution", "source": f"{src}:{cls}"})
        elif cls == "CA":
            m = SEASONAL.search(detail)
            if m and start is not None:
                m1, d1, m2, d2 = map(int, m.groups())
                for y in range(start.year, last_year + 1):
                    s, e = date(y, m1, d1), date(y, m2, d2)
                    if e >= start:
                        rows.append({"growing_area": ga, "area_id": area_id, "start_date": max(s, start),
                                     "end_date": e, "closure_type": "pollution", "source": f"{src}:CA seasonal"})
            else:
                notes.append(f"{area_id} conditionally approved ({(a.get('CA_TYPE') or '').strip()}: {detail}); "
                             "closure events not published, no rows")
    return rows, notes


def report(table: pa.Table, notes: list[str], growing_areas: list[str]) -> str:
    """Markdown report: standing classifications and dated events, and the history each covers (PLAN.md P1.5)."""
    rows = table.to_pylist()
    standing = [r for r in rows if r["end_date"] is None]
    events = [r for r in rows if r["end_date"] is not None]
    lines = ["# Closures report (generated by `oyster-data closures`)", "",
             f"Growing areas: {', '.join(growing_areas)}. Sources: Maine DMR NSSP classification layer (2025) for "
             "standing closures; archived DMR notices for dated events (`sources/dmr_closure_events.py`).", "",
             "| kind | closure type | rows | earliest start | history |", "|---|---|---|---|---|"]
    for t in sorted({r["closure_type"] for r in standing}):
        rs = [r for r in standing if r["closure_type"] == t]
        first = min(r["start_date"] for r in rs)
        lines.append(f"| standing | {t} | {len(rs)} | {first} | classification since {first.year}, no end |")
    for r in events:
        lines.append(f"| event | {r['closure_type']} | 1 | {r['start_date']} | {r['area_id']}, "
                     f"{r['start_date']} to {r['end_date']} |")
    lines += ["| event | biotoxin | 0 | | none naming these areas found in archived DMR notices 2009-2021; 2025 unknown |",
              "", "Notes:", ""]
    lines += [f"- {n}" for n in notes]
    lines += ["", "Both Damariscotta model sites (dam_lower, dam_upper) lie in section WQ:A (Approved) in every "
              "NSSP layer 2015-2025 (point-in-polygon queries, 2026-10-13), so no standing closure applies to them."]
    return "\n".join(lines) + "\n"


def to_closures(growing_areas: list[str], year: int = 2025, last_year: int = 2025,
                raw_dir: Path = RAW_DIR) -> tuple[pa.Table, list[str]]:
    rows, notes = [], []
    for ga in growing_areas:
        data = json.loads(raw_path(year, ga, raw_dir).read_text(encoding="utf-8"))
        r, n = to_rows(data, year, last_year)
        rows += r
        notes += n
    table = pa.Table.from_pylist(rows, schema=arrow_schema("closures"))
    validate_table(table, SPECS["closures"])
    return table, notes
